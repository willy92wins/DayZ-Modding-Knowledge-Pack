function Initialize-VppSuperadmin {
    # VPP superadmin seeding. Layouts differ across VPP versions:
    #   (a) <profiles>\VPPAdminTools\SuperAdmins.json -> {"SUPER_ADMINS":[...]}
    #   (b) <profiles>\VPPAdminTools\Permissions\ (newer, the installed one here):
    #       SuperAdmins\SuperAdmins.txt (one SteamID64 per line) + credentials.txt (login
    #       password on line 1, hashed at first boot, raw then lost). Version (b) IGNORES the
    #       JSON, so seed BOTH. SteamID: -AdminSteamId else retail config. (verified 2026-06-09)
    if ((Get-ModString) -notlike '*VPPAdminTools*') { return }
    $vppDir = Join-Path $ServerProfiles 'VPPAdminTools'

    $ids = @()
    if ($AdminSteamId) { $ids = @($AdminSteamId) }
    else {
        $existing = Join-Path $env:LOCALAPPDATA 'DayZ\VPPAdminTools\SuperAdmins.json'
        if (Test-Path $existing) {
            try { $ids = @((Get-Content $existing -Raw | ConvertFrom-Json).SUPER_ADMINS) } catch { $ids = @() }
        }
    }
    if (-not $ids -or $ids.Count -eq 0) {
        Warn 'No admin SteamID. Pass -AdminSteamId, or set %LOCALAPPDATA%\DayZ\VPPAdminTools\SuperAdmins.json. VPP boots with no superadmin.'
        return
    }

    # (a) legacy JSON — harmless for versions that ignore it; seed only if absent.
    $json = Join-Path $vppDir 'SuperAdmins.json'
    if (-not (Test-Path $json)) {
        New-Item -ItemType Directory -Force -Path $vppDir | Out-Null
        (@{ SUPER_ADMINS = @($ids) } | ConvertTo-Json) | Set-Content -Path $json -Encoding ASCII
    }

    # (b) Permissions\ layout — what the installed VPP actually reads.
    $saTxt = Join-Path $vppDir 'Permissions\SuperAdmins\SuperAdmins.txt'
    New-Item -ItemType Directory -Force -Path (Split-Path $saTxt) | Out-Null
    # Collect candidate IDs (existing file lines + resolved ids), keep ONLY clean 17-digit
    # SteamID64 tokens, dedup. Validating each token prevents string-concatenation corruption
    # and self-heals a previously corrupted file (e.g. two IDs joined into one 34-digit line).
    $merged = [System.Collections.Generic.List[string]]::new()
    $candidates = @()
    if (Test-Path $saTxt) { $candidates += @(Get-Content $saTxt) }
    $candidates += @($ids)
    foreach ($c in $candidates) {
        $s = "$c".Trim()
        if ($s -match '^\d{17}$' -and -not $merged.Contains($s)) { $merged.Add($s) }
    }
    Set-Content -Path $saTxt -Value ($merged -join "`r`n") -Encoding ASCII
    Ok "VPP superadmin(s) -> $saTxt ($($merged -join ', '))"

    # claim: CLAIM-R21-TEST-VPP-SECRET-TEMPLATE
    # credentials.txt: login password on line 1, hashed by VPP at first boot. Seed only when not
    # already set, so an existing hash or user-chosen password is never clobbered.
    $cred = Join-Path $vppDir 'Permissions\credentials.txt'
    $needsPass = $true
    if (Test-Path $cred) {
        $first = (Get-Content $cred | Select-Object -First 1)
        if ($first -match '^[0-9A-Fa-f]{64}$') { $needsPass = $false }
        elseif ($first -and $first.Trim() -and ($first -notmatch '^\s*//')) { $needsPass = $false }
    }
    if ($needsPass) {
        if (-not [string]::IsNullOrWhiteSpace($AdminPass)) {
            New-Item -ItemType Directory -Force -Path (Split-Path $cred) | Out-Null
            Set-Content -Path $cred -Value $AdminPass -Encoding ASCII
            Ok 'VPP login password seeded from -AdminPass (value redacted; VPP hashes it at boot)'
        }
        else { Ok 'VPP password not seeded (passwordless local-dev mode is active)' }
    }
    else { Ok 'VPP credentials.txt already set (not overwriting)' }
}

# ---------------------------------------------------------------------------
# Preflight (DAYZ_INFRA.md secciones "Layout de drives y mods" + "Diag binary" + "serverDZ.cfg")
# ---------------------------------------------------------------------------
function Invoke-Preflight {
    Info 'Preflight...'

    if (-not (Test-Path $Exe)) {
        Die "Game exe not found: $Exe`n       Set DAYZ_GAME_PATH / DAYZ_DIAG_PATH, or verify the DayZ install."
    }
    Ok "exe: $Exe"
    if (-not $Retail -and ($Exe -notlike '*DayZDiag*')) {
        Warn 'Not using DayZDiag — retail exe blocks past the loading screen with -filePatching.'
    }

    if (-not (Test-Path $WorkDrive)) { Die "Work drive $WorkDrive not mounted. See DAYZ_INFRA.md (P:\ symlink)." }
    Ok "work drive: $WorkDrive"

    # P:\Mods MUST be a junction to <DayZ>\!Workshop so deployed PBOs land where the engine reads.
    if (-not (Test-Path $ModsDir)) {
        Warn "$ModsDir missing. Creating junction -> $Workshop"
        & cmd /c mklink /J "$ModsDir" "$Workshop" | Out-Null
        if (-not (Test-Path $ModsDir)) { Die "Failed to create junction $ModsDir." }
        Ok "junction created: $ModsDir -> $Workshop"
    }
    else {
        $item = Get-Item $ModsDir -Force
        if ($item.LinkType -eq 'Junction') { Ok "junction ok: $ModsDir" }
        else { Warn "$ModsDir exists but is NOT a junction. Deployed mods may not be seen by the engine." }
    }

    # Server workspace + serverDZ.cfg with allowFilePatching = 1.
    if ($Mode -in @('server', 'client', 'all')) {
        if (-not (Test-Path $ServerWs)) { New-Item -ItemType Directory -Force -Path $ServerWs | Out-Null }
        if (-not (Test-Path $ServerProfiles)) { New-Item -ItemType Directory -Force -Path $ServerProfiles | Out-Null }
        if (-not (Test-Path $ServerCfg)) {
            New-ServerCfg -Path $ServerCfg -Template $script:MissionPath
            Ok "generated serverDZ.cfg (allowFilePatching=1): $ServerCfg"
        }
        else {
            $cfg = Get-Content $ServerCfg -Raw
            if ($cfg -match 'allowFilePatching\s*=\s*1') { Ok 'serverDZ.cfg: allowFilePatching = 1' }
            else { Die "serverDZ.cfg has allowFilePatching != 1 -> BattlEye kick 0x00020005. Fix: $ServerCfg" }
            # Self-heal: cfgs generated before the vppDisablePassword default (pre 2026-06-09) lack it,
            # leaving a VPP superadmin stuck at the password prompt. Append it if absent.
            if ($cfg -notmatch 'vppDisablePassword') {
                Add-Content -Path $ServerCfg -Value 'vppDisablePassword = 1;        // auto-added: VPP passwordless admin for SuperAdmins.txt superadmins (dev). Remove for password-gated testing.'
                Ok 'serverDZ.cfg: appended vppDisablePassword = 1 (VPP passwordless admin)'
            }
            else { Ok 'serverDZ.cfg: vppDisablePassword present' }
        }
        Initialize-VppSuperadmin
    }
    if ($Mode -in @('offline', 'client', 'all')) {
        if (-not (Test-Path $ClientProfiles)) { New-Item -ItemType Directory -Force -Path $ClientProfiles | Out-Null }
        $steamKey = 'HKCU:\Software\Valve\Steam\ActiveProcess'
        $steamFailure = 'The DayZ client will die at bootstrap with a ~1 KB RPT and an ErrorMessage_*.mdmp. Recovery: run steam.exe -shutdown, then relaunch Steam. Your login is preserved; no re-login is required, and the registry key repopulates in ~20 s.'
        try {
            $steam = Get-ItemProperty -LiteralPath $steamKey -ErrorAction Stop
            $steamProcessId = [int64]$steam.pid
            $steamActiveUser = [int64]$steam.ActiveUser
            if (($steamProcessId -ne 0) -and ($steamActiveUser -ne 0)) {
                Ok "Steam session: pid=$steamProcessId ActiveUser=$steamActiveUser"
            }
            else {
                Warn "STEAM CLIENT PREFLIGHT: unusable session (pid=$steamProcessId ActiveUser=$steamActiveUser). $steamFailure"
            }
        }
        catch {
            Warn "STEAM CLIENT PREFLIGHT: registry key missing or unreadable ($steamKey). $steamFailure"
        }
    }

    if ($Build -or $Clean) {
        if (-not (Test-Path $AddonBuilder)) { Die "AddonBuilder not found: $AddonBuilder (set DAYZ_TOOLS_PATH)." }
        Ok "AddonBuilder: $AddonBuilder"
    }

    Ok "mission: $script:MissionPath"
    Info 'Preflight passed.'
}

# ---------------------------------------------------------------------------
# Build + deploy (DAYZ_INFRA.md seccion "Comandos de invocacion canonicos" - AddonBuilder)
# ---------------------------------------------------------------------------
function Invoke-Build {
    $src = if ($Source) { $Source } else { Join-Path $WorkDrive $Mod }
    if (-not (Test-Path $src)) { Die "Mod source not found: $src (pass -Source, or junction P:\$Mod -> your editable folder)." }
    $target = Join-Path $ModsDir "@$Mod\Addons"
    $temp   = Join-Path $WorkDrive "temp\$Mod"
    if (-not (Test-Path $target)) { New-Item -ItemType Directory -Force -Path $target | Out-Null }

    # AddonBuilder's incremental sync to $temp can serve STALE source: a changed .c may
    # silently not be re-copied (observed 2026-06-18: a deviceinspector.c months out of date
    # was packed into the PBO, so script edits never reached the build and the diag kept
    # compiling old code — a fix appeared to "not take" across several rebuilds). Wipe the
    # temp staging before every build so the sync is always fresh. Costs incremental reuse
    # (full re-binarize) but a stale build is a silent correctness disaster that masks edits.
    if (Test-Path $temp) { Remove-Item -LiteralPath $temp -Recurse -Force -ErrorAction SilentlyContinue }

    # AddonBuilder's default (binarize) mode does NOT copy .c scripts (not in its include-list):
    # a scripts-only mod then packs to a config-only PBO and nothing runs in-game. Use -packonly
    # (copies all as-is) when the source has no binarizable assets, or force it with -PackOnly.
    # Verified 2026-06-03 (a scripts mod packed to 662 b under binarize, 124 KB under -packonly).
    $hasAssets   = @(Get-ChildItem $src -Recurse -Include *.p3d, *.paa, *.rvmat -File -ErrorAction SilentlyContinue).Count -gt 0
    $usePackOnly = $PackOnly -or (-not $hasAssets)

    Info "Build: $src -> $target$(if ($usePackOnly) { ' (-packonly)' })"
    $abArgs = @("`"$src`"", "`"$target`"", "-prefix=$Mod", "`"-temp=$temp`"")
    if ($Clean) { $abArgs += '-clear' }
    if ($usePackOnly) { $abArgs += '-packonly' }
    $p = Start-Process -FilePath $AddonBuilder -ArgumentList $abArgs -Wait -NoNewWindow -PassThru
    if ($p.ExitCode -ne 0) { Die "AddonBuilder failed (exit $($p.ExitCode)). Check config.cpp / paths." }
    $pbo = Join-Path $target "$Mod.pbo"
    if (-not (Test-Path $pbo)) { Die "Build reported success but $pbo is missing." }
    # Sanity: a mod with scripts that packs tiny means binarize dropped the .c (include-list).
    if ((Test-Path (Join-Path $src 'scripts')) -and ((Get-Item $pbo).Length -lt 4096)) {
        Warn "PBO is only $((Get-Item $pbo).Length) b but the mod has scripts\ - binarize likely dropped the .c. Re-run with -PackOnly."
    }
    Ok "deployed: $pbo ($((Get-Item $pbo).Length) b)"
}

